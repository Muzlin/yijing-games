class GameRegistry {
  static TurnGame create(GameKind kind, {int boardSize = 0}) {
    switch (kind) {
      case GameKind.gomoku:
        return GomokuGame();
      case GameKind.reversi:
        return ReversiGame();
      case GameKind.connect4:
        return ConnectFourGame();
      case GameKind.connect6:
        return ConnectSixGame();
      case GameKind.nineMensMorris:
        return NineMensMorrisGame();
      case GameKind.amazons:
        return AmazonsGame();
      case GameKind.tiger:
        return TigerGame();
      case GameKind.chineseCheckers:
        return ChineseCheckersGame();
      case GameKind.flyingChess:
        return FlyingChessGame();
      case GameKind.backgammon:
        return BackgammonGame();
      case GameKind.shogi:
        return ShogiGame();
      case GameKind.tycoon:
        return TycoonGame();
      case GameKind.doudizhu:
        return DouDizhuGame();
      case GameKind.mahjong:
        return MahjongGame();
      case GameKind.ticTacToe:
        return TicTacToeGame();
      case GameKind.fiveFieldKono:
        return FiveFieldKonoGame();
      case GameKind.hex:
        return HexGame();
      case GameKind.dotsBoxes:
        return DotsBoxesGame();
      case GameKind.mancala:
        return MancalaGame();
      case GameKind.oware:
        return OwareGame();
      case GameKind.hareHounds:
        return HareHoundsGame();
      case GameKind.foxGeese:
        return FoxGeeseGame();
      case GameKind.quoridor:
        return QuoridorGame();
      case GameKind.twelveMensMorris:
        return TwelveMensMorrisGame();
      case GameKind.sixMensMorris:
        return SixMensMorrisGame();
      case GameKind.threeMensMorris:
        return ThreeMensMorrisGame();
      case GameKind.quarto:
        return QuartoGame();
      case GameKind.yote:
        return YoteGame();
      case GameKind.onitama:
        return OnitamaGame();
      case GameKind.go:
        return GoGame(size: boardSize == 13 ? 13 : 9);
      case GameKind.xiangqi:
        return XiangqiGame();
      case GameKind.draughts:
        return DraughtsGame();
      case GameKind.jungle:
        return JungleGame();
      case GameKind.junqi:
        return JunqiGame();
      case GameKind.snakes:
        return SnakesGame();
      default:
        throw UnsupportedError('Game $kind is not wired yet');
    }
  }
}
